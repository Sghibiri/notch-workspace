import AppKit
import Combine

@MainActor
final class ClipboardService: ObservableObject {
    @Published private(set) var history = ClipboardHistory()
    @Published private(set) var blockedBySystem = false
    @Published var enabled: Bool {
        didSet { defaults.set(enabled, forKey: "clipboardEnabled"); lastChange = pasteboard.changeCount; updateMonitoring() }
    }
    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private var lastChange: Int
    private var timer: Timer?
    private var workspaceObserver: NSObjectProtocol?
    private var lockObserver: NSObjectProtocol?
    private var activationObserver: NSObjectProtocol?
    private let monitoringAllowed: Bool
    private let accessOverride: (() -> Bool)?
    private let excludedApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "com.keepassxc.keepassxc"
    ]
    init(pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard, startMonitoring: Bool = true, accessAllowed: (() -> Bool)? = nil) {
        self.pasteboard = pasteboard
        self.defaults = defaults
        monitoringAllowed = startMonitoring
        accessOverride = accessAllowed
        enabled = defaults.bool(forKey: "clipboardEnabled")
        lastChange = pasteboard.changeCount
        if startMonitoring {
            updateMonitoring()
            workspaceObserver = NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.sessionDidResignActiveNotification, object: nil, queue: .main) { [weak self] _ in
                Task { @MainActor in self?.history.clear() }
            }
            lockObserver = DistributedNotificationCenter.default().addObserver(forName: .init("com.apple.screenIsLocked"), object: nil, queue: .main) { [weak self] _ in
                Task { @MainActor in self?.history.clear() }
            }
            activationObserver = NotificationCenter.default.addObserver(forName: NSApplication.didBecomeActiveNotification, object: nil, queue: .main) { [weak self] _ in
                Task { @MainActor in if self?.blockedBySystem == true { self?.recheckAccess() } }
            }
        }
    }
    private func updateMonitoring() {
        timer?.invalidate()
        timer = nil
        guard enabled else { blockedBySystem = false; return }
        guard hasSystemAccess(), monitoringAllowed else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.75, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.captureIfChanged() }
        }
        timer?.tolerance = 0.2
    }
    func captureIfChanged() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard enabled else { return }
        guard hasSystemAccess() else { timer?.invalidate(); timer = nil; return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]),
              !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
              !excludedApps.contains(NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? ""),
              let text = pasteboard.string(forType: .string) else { return }
        history.insert(text)
    }
    private func hasSystemAccess() -> Bool {
        let allowed: Bool
        if let accessOverride { allowed = accessOverride() }
        else if #available(macOS 15.4, *), pasteboard.name == .general {
            allowed = pasteboard.accessBehavior != .alwaysDeny
        } else { allowed = true }
        if blockedBySystem == allowed { blockedBySystem = !allowed }
        return allowed
    }
    func recheckAccess() {
        lastChange = pasteboard.changeCount
        updateMonitoring()
    }
    func copy(_ entry: ClipboardEntry) {
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        lastChange = pasteboard.changeCount
    }
    func remove(_ id: UUID) { history.remove(id) }
    func clear() { history.clear() }
    func seedPreview() {
        history.insert("https://developer.apple.com/swift/")
        history.insert("Keep the useful things close. Let everything else get out of the way.")
        history.insert("A little space for your next great idea.")
    }
    deinit {
        timer?.invalidate()
        if let workspaceObserver { NSWorkspace.shared.notificationCenter.removeObserver(workspaceObserver) }
        if let lockObserver { DistributedNotificationCenter.default().removeObserver(lockObserver) }
        if let activationObserver { NotificationCenter.default.removeObserver(activationObserver) }
    }
}
